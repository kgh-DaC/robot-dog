"""Embed index.html into the ESP32 firmware as tools/servoInitPose/web_page.h.

Run after editing index.html, then rebuild/upload the firmware:
    python embed_page.py
The USB gateway serves index.html directly, so both links show the same page.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "index.html"
TARGET = HERE.parents[1] / "tools" / "servoInitPose" / "web_page.h"
DELIMITER = "HTML"


def build_header(html: str) -> str:
    if f"){DELIMITER}\"" in html:
        raise ValueError("index.html contains the raw-string delimiter")
    return (
        "// Generated by software/robot_control_web/embed_page.py from index.html.\n"
        "// Do not edit by hand.\n"
        "#pragma once\n\n"
        f"const char ROBOT_CONTROL_PAGE[] PROGMEM = R\"{DELIMITER}({html}){DELIMITER}\";\n"
    )


def main() -> None:
    header = build_header(SOURCE.read_text(encoding="utf-8"))
    TARGET.write_text(header, encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET} ({len(header.encode('utf-8'))} bytes)")


if __name__ == "__main__":
    main()
